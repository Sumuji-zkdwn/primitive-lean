"""Check the linear-input proofs and their actual Elastica connections together.

Builds the parent's pinned Elastica library, imports its actual declarations,
then checks the linear-input source and bridge statements with --trust=0.
All.lean is generated by collecting imports and concatenating the exact parts.
Every local declaration in both proof groups is axiom-audited in this session.
"""
from pathlib import Path
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
import re
import subprocess
import time

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
PROJECT = ROOT / "lean"
PROOFS = HERE / "lean_check"
PARTS = ("Design.lean", "Observation.lean", "Calculus.lean", "Consequences.inc",
         "Coercivity.inc", "Gradient.inc", "Dissipation.lean", "RegularBand.inc",
         "Invariance.inc", "CurvatureBridge.inc", "VariationalBridge.inc", "Feedback.inc",
         "Constraints.inc", "AreaVariation.inc", "PressureCurvature.inc", "PressureStationary.inc",
         "AreaRegularity.inc", "AreaParameters.inc", "AreaFamily.inc",
         "AreaExactVariation.inc", "AreaMinimum.inc", "StrictEnergy.inc",
         "GradientBound.inc", "InternalUpdate.inc", "TrajectoryExistence.inc",
         "FiniteBand.inc", "CompactLocalExistence.inc", "GlobalContinuation.inc",
         "GlobalTrajectory.inc", "ForwardUniqueness.inc", "GlobalConsequences.inc",
         "LevelGeometry.inc", "FiniteInternalUpdate.inc", "CoupledTrajectory.inc",
         "LevelConvergence.inc", "CoupledConsequences.inc")
ALLOWED = {"propext", "Classical.choice", "Quot.sound"}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(command, log):
    started = time.monotonic()
    p = subprocess.run(command, cwd=PROJECT, encoding="utf-8", errors="replace",
                       capture_output=True)
    text = p.stdout + p.stderr
    (PROOFS / log).write_text(text, encoding="utf-8")
    return dict(command=command, working_directory=str(PROJECT), exit_code=p.returncode,
                seconds=round(time.monotonic() - started, 3), log="lean_check/" + log), text


def main():
    spec = importlib.util.spec_from_file_location("parent_verifier", ROOT / "tools/verify.py")
    old = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(old)
    imports, bodies, declarations, hashes, forbidden = [
        "import Elastica",
        "import Mathlib.Data.Complex.Basic",
        "import Mathlib.Data.ZMod.Basic",
        "import Mathlib.RingTheory.Polynomial.Cyclotomic.Roots",
        "import Mathlib.LinearAlgebra.Matrix.Rank",
        "import Mathlib.LinearAlgebra.Matrix.Determinant.Basic",
        "import Mathlib.Algebra.BigOperators.Fin",
        "import Mathlib.FieldTheory.KummerExtension",
        "import Mathlib.GroupTheory.SpecificGroups.Dihedral",
    ], [], [], {}, []
    parent_declarations = []
    for path in sorted((PROJECT / "Elastica").glob("*.lean")):
        rel = "../lean/" + path.relative_to(PROJECT).as_posix()
        hashes[rel] = sha(path)
        code = old.strip_comments_strings(path.read_text(encoding="utf-8"))
        for found in re.finditer(r"\b(sorry|admit|axiom|unsafe|native_decide)\b", code):
            forbidden.append(dict(file=rel, token=found.group(),
                                  line=code.count("\n", 0, found.start()) + 1))
        for found in re.finditer(r"(?m)^(?:@\[[^\n]*\]\s*)?(theorem|lemma|def|abbrev)\s+([^\s({:]+)", code):
            parent_declarations.append(dict(
                name="Elastica." + found.group(2), kind=found.group(1),
                file=rel, line=code.count("\n", 0, found.start()) + 1,
            ))
    for name in PARTS:
        path = PROOFS / name
        raw = path.read_text(encoding="utf-8")
        hashes["lean_check/" + name] = sha(path)
        body_lines = []
        for line in raw.splitlines():
            if line.startswith("import "):
                if line not in imports:
                    imports.append(line)
            else:
                body_lines.append(line)
        bodies.append("-- Source: " + name + "\n" + "\n".join(body_lines))
        code = old.strip_comments_strings(raw)
        namespaces = re.findall(r"(?m)^namespace\s+(\w+)", code)
        assert len(namespaces) == 1, (name, namespaces)
        namespace = namespaces[0]
        for found in re.finditer(r"\b(sorry|admit|axiom|unsafe|native_decide)\b", code):
            forbidden.append(dict(file=name, token=found.group(),
                                  line=code.count("\n", 0, found.start()) + 1))
        for found in re.finditer(r"(?m)^(theorem|lemma|def|abbrev)\s+(\w+)", code):
            declarations.append(dict(
                name=namespace + "." + found.group(2), kind=found.group(1),
                file="lean_check/" + name, line=code.count("\n", 0, found.start()) + 1,
            ))
    source = "\n".join(imports) + "\n\n" + "\n\n".join(bodies)
    audited_declarations = parent_declarations + declarations
    source += "\n\n-- Audit the imported Elastica declarations and all linear-input declarations.\n"
    source += "\n".join("#print axioms " + item["name"] for item in audited_declarations) + "\n"
    (PROOFS / "All.lean").write_text(source, encoding="utf-8")
    hashes["lean_check/All.lean"] = sha(PROOFS / "All.lean")
    parent_build, _ = run(["lake", "build", "Elastica"], "elastica-build.log")
    compile_result, log = run(
        ["lake", "env", "lean", "--trust=0", "../linear_input/lean_check/All.lean"], "build.log")
    axioms, unexpected = {}, []
    for item in audited_declarations:
        name = item["name"]
        match = re.search("'" + re.escape(name) + r"' depends on axioms: \[([^]]*)\]", log, re.S)
        if match:
            found = [x.strip() for x in match.group(1).split(",") if x.strip()]
        elif "'" + name + "' does not depend on any axioms" in log:
            found = []
        else:
            unexpected.append(name + ": missing audit result")
            continue
        axioms[name] = found
        unexpected.extend(name + ": " + ax for ax in found if ax not in ALLOWED)
    manifest = json.loads((PROJECT / "lake-manifest.json").read_text(encoding="utf-8"))
    revisions = []
    for pkg in manifest["packages"]:
        proc = subprocess.run(["git", "rev-parse", "HEAD"],
            cwd=PROJECT / ".lake/packages" / pkg["name"],
            capture_output=True, encoding="utf-8")
        actual = proc.stdout.strip()
        revisions.append(dict(name=pkg["name"], expected=pkg["rev"], actual=actual,
                              match=proc.returncode == 0 and actual == pkg["rev"]))
    version = subprocess.run(["lake", "env", "lean", "--version"],
        cwd=PROJECT, capture_output=True, encoding="utf-8").stdout.strip()
    for name in ("Elastica.lean", "lean-toolchain", "lakefile.toml", "lake-manifest.json"):
        hashes["../lean/" + name] = sha(PROJECT / name)
    hashes["verify_lean.py"] = sha(Path(__file__))
    passed = parent_build["exit_code"] == 0 and compile_result["exit_code"] == 0 and not forbidden and not unexpected \
        and all(p["match"] for p in revisions)
    report = {
        "passed": passed, "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "version": version, "compile": compile_result,
        "parent_library_build": {**parent_build, "clean_build": False},
        "theorem_count": sum(x["kind"] in ("theorem", "lemma") for x in declarations),
        "declaration_count": len(declarations), "declarations": declarations,
        "parent_theorem_count": sum(x["kind"] in ("theorem", "lemma") for x in parent_declarations),
        "parent_declaration_count": len(parent_declarations),
        "parent_declarations": parent_declarations,
        "joint_axiom_audit": True,
        "axioms": {d["name"]: axioms[d["name"]] for d in declarations if d["name"] in axioms},
        "parent_axioms": {d["name"]: axioms[d["name"]] for d in parent_declarations if d["name"] in axioms},
        "unexpected": unexpected, "forbidden_tokens": forbidden,
        "dependencies": revisions, "source_sha256": hashes,
        "scope": "Current Elastica library build followed by fresh --trust=0 checking of linear-input proofs and actual variational/curvature bridges, including exact-area constrained C1 local minima, constructed correction families, pressure uniqueness, exact energy-gap evolution, and explicit gradient bounds. Generic local existence on complete real normed spaces, compact continuation, and forward uniqueness support actual forward-global coupled solutions with any finite number of positively damped internal coordinates, C1 full-state tangential feedback, and C1 spatial-only forcing. Finite-interval internal bounds establish compact box confinement before continuation; b=1+Q^2 and finite coefficient expansions are connected. Actual level and band homeomorphisms support a constructive radial target-point distance estimate in the product maximum metric. The explicit exponential distance bound and distance-to-level limit, energy convergence, and strict-gap spatial nonreturn are applied to the constructed coupled solution from initial data. Public declarations from both groups and dependencies of private helpers are axiom-audited in the same Lean session. Parent Elastica source and its historical report remain unchanged; its current source hashes are included here.",
        "not_covered": ["JavaScript or Python floating-point execution", "cubic root-count classification",
                        "convex-conjugate and envelope theorems",
                        "smooth level parametrizations and diffeomorphisms of energy bands",
                        "global existence for arbitrary time-dependent feedback or unrestricted internal-state-dependent forcing",
                        "optimal gradient lower bounds or optimal convergence rates",
                        "boundedness and continuation of arbitrary or infinite-dimensional internal-state updates",
                        "convergence to a spatial point, convergence of the internal state, periodic limiting trajectories or asymptotic phase",
                        "existence and regularity of area-constrained minimizing curves",
                        "unconditional uniqueness or nonzero pressure multiplier for every area-constrained stationary curve",
                        "local minima of prescribed-pressure functionals at singular straight endpoint constraints",
                        "unique physical-time dynamics or internal update law from static elastica"],
    }
    (HERE / "lean_results.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    summary = {k: report[k] for k in
               ("passed", "version", "theorem_count", "declaration_count", "parent_theorem_count",
                "parent_declaration_count", "parent_library_build", "compile",
                "unexpected", "forbidden_tokens")}
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    if not passed:
        print(log)
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
