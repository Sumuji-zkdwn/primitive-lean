"""Finite certificates for associative recovery of an observation-based hyperquotient.

Standard library only: python -m unittest -v test_void_multivalued_completion.py

The operation is total, deterministic and associative on concrete states.  A
coarse observer reports one of k blocks.  Its hyperquotient may not be
associative; the subsemigroup of exact nonempty subsets generated by its
blocks always is.  Inputs at distinct leaves are independent choices.
"""
from collections import Counter
from itertools import product
import unittest


def partitions(n):
    """Canonical restricted-growth strings for all set partitions."""
    def visit(prefix):
        if len(prefix) == n:
            yield tuple(prefix)
        else:
            for j in range(max(prefix) + 2):
                yield from visit(prefix + [j])
    if n:
        yield from visit([0])


def assoc(table, n):
    return all(table[table[a*n+b]*n+c] == table[a*n+table[b*n+c]]
               for a, b, c in product(range(n), repeat=3))


def classes(blocks):
    return tuple(frozenset(x for x, p in enumerate(blocks) if p == k)
                 for k in range(max(blocks) + 1))


def congruent(table, blocks):
    n = len(blocks)
    return all(blocks[table[a*n+b]] == blocks[table[c*n+d]]
               for a,b,c,d in product(range(n), repeat=4)
               if blocks[a] == blocks[c] and blocks[b] == blocks[d])


def set_product(table, n, A, B):
    return frozenset(table[a*n+b] for a in A for b in B)


def abstract(table, blocks):
    n = len(blocks)
    fibers = classes(blocks)
    return {(i, j): frozenset(blocks[x] for x in set_product(table,n,A,B))
            for i,A in enumerate(fibers) for j,B in enumerate(fibers)}


def associativity_defects(hyper, k):
    """Return (left-spurious, right-spurious) for all defective label triples."""
    for a,b,c in product(range(k),repeat=3):
        left = set().union(*(hyper[d,c] for d in hyper[a,b]))
        right = set().union(*(hyper[a,d] for d in hyper[b,c]))
        if left != right:
            yield (a,b,c,frozenset(left),frozenset(right))


def is_product_saturated(table, blocks):
    """Sufficient, not necessary, for associative hyperquotient."""
    n=len(blocks)
    fibers=classes(blocks)
    for A,B in product(fibers,repeat=2):
        exact=set_product(table,n,A,B)
        sat=frozenset(x for x in range(n) if blocks[x] in {blocks[z] for z in exact})
        if sat != exact:
            return False
    return True


def generated_exact_sets(table, blocks):
    """Least subsemigroup of P(S) containing all nonempty observation fibers."""
    n=len(blocks)
    sets=set(classes(blocks))
    while True:
        next_sets=sets|{set_product(table,n,A,B) for A,B in product(sets,repeat=2)}
        if next_sets == sets:
            return frozenset(sets)
        sets=next_sets


def observed_outputs(subset, blocks):
    return frozenset(blocks[s] for s in subset)


def stable_partition(table, subsets, blocks):
    """Maximum contextual congruence on the finite generated exact-set semigroup."""
    n=len(blocks)
    subsets=sorted(subsets, key=lambda x: (len(x),tuple(sorted(x))))
    def labels_of(signatures):
        lookup={}
        return tuple(lookup.setdefault(s,len(lookup)) for s in signatures)
    partition=labels_of([observed_outputs(A,blocks) for A in subsets])
    history=[partition]
    while True:
        signatures=[]
        for A in subsets:
            i=subsets.index(A)
            right=tuple(partition[subsets.index(set_product(table,n,A,B))] for B in subsets)
            left=tuple(partition[subsets.index(set_product(table,n,B,A))] for B in subsets)
            signatures.append((partition[i],right,left))
        updated=labels_of(signatures)
        if updated == partition:
            return subsets,history
        history.append(updated)
        partition=updated


class VoidMultivaluedCompletion(unittest.TestCase):
    @staticmethod
    def nilpotent_model():
        # 0 annihilates everything; v*v = u; remaining products are 0.
        table=tuple(1 if (i,j)==(2,2) else 0
                    for i,j in product(range(3),repeat=2))
        return table,(0,1,0)  # A={0,v}, B={u}

    def test_minimal_nonassociative_hyperquotient(self):
        table,blocks=self.nilpotent_model()
        self.assertTrue(assoc(table,3))
        h=abstract(table,blocks)
        self.assertEqual(list(associativity_defects(h,2)),[
            (0,0,1, frozenset({0}),frozenset({0,1})),
            (0,1,1, frozenset({0}),frozenset({0,1})),
            (1,0,0, frozenset({0,1}),frozenset({0})),
            (1,1,0, frozenset({0,1}),frozenset({0})),
        ])
        # The right association invents a hidden v after A*B={0}.
        A,B=classes(blocks)
        exact_triple=set_product(table,3,set_product(table,3,A,A),B)
        self.assertEqual(exact_triple,frozenset({0}))

    def test_exact_repair_four_states_and_minimality(self):
        table,blocks=self.nilpotent_model()
        A,B=classes(blocks)
        C=set_product(table,3,A,A)
        D=set_product(table,3,A,B)
        self.assertEqual((A,B,C,D),(
            frozenset({0,2}),frozenset({1}),frozenset({0,1}),frozenset({0})))
        generated=generated_exact_sets(table,blocks)
        self.assertEqual(generated,frozenset({A,B,C,D}))
        for X,Y,Z in product(generated,repeat=3):
            self.assertEqual(set_product(table,3,set_product(table,3,X,Y),Z),
                             set_product(table,3,X,set_product(table,3,Y,Z)))
        states,history=stable_partition(table,generated,blocks)
        self.assertEqual(len(set(history[-1])),4)
        self.assertEqual(len(history),2)
        # A and D have identical present observations; joining A reveals a difference.
        self.assertEqual(observed_outputs(A,blocks),observed_outputs(D,blocks))
        self.assertNotEqual(observed_outputs(set_product(table,3,A,A),blocks),
                            observed_outputs(set_product(table,3,D,A),blocks))
        # Hence all four exact-set states are necessary for a deterministic,
        # context-compositional encoding preserving every future output.

    def test_complete_three_state_census(self):
        count=Counter()
        for table in product(range(3),repeat=9):
            if not assoc(table,3):
                continue
            for blocks in partitions(3):
                deterministic=congruent(table,blocks)
                h=abstract(table,blocks)
                associative=not any(associativity_defects(h,max(blocks)+1))
                saturated=is_product_saturated(table,blocks)
                count[(deterministic,associative,saturated)]+=1
                if not associative:
                    generated=generated_exact_sets(table,blocks)
                    _,history=stable_partition(table,generated,blocks)
                    self.assertEqual(len(classes(blocks)),2)
                    self.assertEqual(len(generated),4)
                    self.assertEqual(len(set(history[-1])),4)
                if deterministic:
                    self.assertTrue(associative)
                if saturated:
                    self.assertTrue(associative)
        self.assertEqual(sum(count.values()),565)
        self.assertEqual(sum(v for (c,a,s),v in count.items() if c),409)
        self.assertEqual(sum(v for (c,a,s),v in count.items() if not c and a),126)
        self.assertEqual(sum(v for (c,a,s),v in count.items() if not a),30)
        self.assertEqual(count[(False,True,True)],24)
        self.assertEqual(count[(False,True,False)],102)

    def test_group_orbit_as_sufficient_not_necessary(self):
        n=6
        table=tuple((i+j)%n for i,j in product(range(n),repeat=2))
        orbit=tuple((0,1,2,3,2,1))
        self.assertTrue(assoc(table,n))
        self.assertFalse(congruent(table,orbit))
        self.assertTrue(is_product_saturated(table,orbit))
        self.assertFalse(any(associativity_defects(abstract(table,orbit),4)))
        # Contrast: failure of saturation does not imply failure of associativity.
        three_state=tuple(1 if (a,b)==(2,2) else 0
                          for a,b in product(range(3),repeat=2))
        other_blocks=(0,1,1)
        self.assertFalse(congruent(three_state,other_blocks))
        self.assertFalse(is_product_saturated(three_state,other_blocks))
        self.assertFalse(any(associativity_defects(abstract(three_state,other_blocks),2)))


if __name__ == '__main__':
    unittest.main()